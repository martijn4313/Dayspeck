"""PlatformIO pre-build script: gzips the web UI, firmware/web/index.html, into a header for the firmware.

The page is served with Content-Encoding: gzip, so the firmware holds a quarter of its size: that leaves room
for an over-the-air update next to it. The header goes to the build folder (index_html_gz.h, index_html_gz[]),
and is only rewritten when the page changed, so an unchanged page does not rebuild webserver.cpp.
"""
import gzip
from pathlib import Path

Import("env")  # noqa: F821  (provided by PlatformIO's SCons)

root = Path(env.subst("$PROJECT_DIR"))  # noqa: F821
page = root / "firmware" / "web" / "index.html"
out_dir = Path(env.subst("$BUILD_DIR")) / "generated"  # noqa: F821
out = out_dir / "index_html_gz.h"

data = gzip.compress(page.read_bytes(), compresslevel=9, mtime=0)   # mtime 0: the same page, the same bytes
rows = (", ".join(str(b) for b in data[i:i + 24]) for i in range(0, len(data), 24))
text = ("// Generated by tools/pio_webui.py from firmware/web/index.html: do not edit\n"
        "#pragma once\n#include <pgmspace.h>\n"
        f"static const uint8_t index_html_gz[{len(data)}] PROGMEM = {{\n" + ",\n".join(rows) + "\n};\n")
out_dir.mkdir(parents=True, exist_ok=True)
if not out.exists() or out.read_text() != text:
    out.write_text(text)
env.Append(CPPPATH=[str(out_dir)])  # noqa: F821
print(f"Web UI: {page.stat().st_size} bytes, gzipped {len(data)}")
